-- 1) One row of saved study state per user (progress, schedule profile, study log).
create table if not exists public.user_state (
  user_id uuid primary key references auth.users (id) on delete cascade,
  state jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
alter table public.user_state enable row level security;

create policy "read own state" on public.user_state
  for select using (auth.uid() = user_id);
create policy "insert own state" on public.user_state
  for insert with check (auth.uid() = user_id);
create policy "update own state" on public.user_state
  for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- 2) Internal resources: titles, summaries and links only readable by allow-listed emails.
create table if not exists public.allowed_emails (
  email text primary key
);
alter table public.allowed_emails enable row level security; -- no policies: clients can never read it

create or replace function public.is_allowed()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.allowed_emails
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

create table if not exists public.internal_resources (
  id bigint generated by default as identity primary key,
  title text not null,
  summary text,
  url text,
  stage text,
  sort int not null default 0
);
alter table public.internal_resources enable row level security;

create policy "allow-listed users can read" on public.internal_resources
  for select using (public.is_allowed());

